"""Embeds the placeholder model and its numpy goldens as a C header for the
on-device self-test (examples/selftest):

    python research/make_selftest_data.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "test", "data")
OUT = os.path.join(HERE, "..", "examples", "selftest", "selftest_data.h")


def array(name, data):
    lines = [f"alignas(16) static const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const size_t {name}_len = {len(data)};")
    return "\n".join(lines)


def main():
    model = open(os.path.join(DATA, "placeholder_model.tstt"), "rb").read()
    golden = open(os.path.join(DATA, "model_golden.bin"), "rb").read()
    with open(OUT, "w") as f:
        f.write("// generated by research/make_selftest_data.py - do not edit\n#pragma once\n#include <stdint.h>\n\n")
        f.write(array("selftest_model", model) + "\n\n" + array("selftest_golden", golden) + "\n")
    print(f"wrote {OUT}: model {len(model)} B, golden {len(golden)} B")


if __name__ == "__main__":
    main()
