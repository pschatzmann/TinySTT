"""Makes the model containers in data/ available to sketches as arrays that
are compiled into the program and used in place from flash.

    python research/embed_model.py              # every data/*.tstt
    python research/embed_model.py my.tstt      # other containers

For each container <name>.tstt this writes three files to src/TinySTT/data/,
all part of the library (no step needed by its users):
- <name>_model.S.bin: a copy of the container;
- <name>_model.S: the assembler directive .incbin includes <name>_model.S.bin
  into the read-only data (flash) when a sketch is compiled, 16 byte
  aligned. It names the file as __FILE__ (the absolute path of the .S file,
  from the preprocessor) plus ".bin", so it works wherever the library is
  installed and with every toolchain (the assemblers do not all search the
  include paths);
- <name>_model.h: declares <name>_model[] and <name>_model_size().

A sketch then uses the model without a load step and without a RAM copy:

    #include "TinySTT/data/tinystt_model.h"
    model.begin(tinystt_model, tinystt_model_size());

Sketches that do not use a model do not grow: the linker drops unreferenced
sections. Run the script again when a model in data/ changes.
"""
import argparse
import glob
import os
import re
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "TinySTT", "data")

ASM = """// {name}_model: {file} ({size} bytes) included at compile time from
// {name}_model.S.bin (__FILE__ + ".bin"). Generated by research/embed_model.py,
// see docs/model-embedding.md.
  .macro tinystt_incbin path
  .incbin "\\path\\().bin"
  .endm
  .section .rodata.{name}_model, "a"
  .balign 16
  .global {name}_model
{name}_model:
  tinystt_incbin __FILE__
  .global {name}_model_end
{name}_model_end:
"""

HEADER = """// {name}_model: {file} ({size} bytes), included by {name}_model.S.
// Generated by research/embed_model.py, see docs/model-embedding.md.
#pragma once
#include <stddef.h>
#include <stdint.h>

extern "C" const uint8_t {name}_model[], {name}_model_end[];

/// size of the model container in bytes
inline size_t {name}_model_size() {{ return {name}_model_end - {name}_model; }}
"""


def embed(container):
    path = os.path.abspath(container)
    file = os.path.basename(path)
    name = re.sub(r"\W", "_", os.path.splitext(file)[0])
    size = os.path.getsize(path)
    os.makedirs(OUT, exist_ok=True)
    shutil.copyfile(path, os.path.join(OUT, name + "_model.S.bin"))
    with open(os.path.join(OUT, name + "_model.S"), "w") as f:
        f.write(ASM.format(name=name, file=file, size=size))
    with open(os.path.join(OUT, name + "_model.h"), "w") as f:
        f.write(HEADER.format(name=name, file=file, size=size))
    print(f"{file} ({size} bytes) -> src/TinySTT/data/{name}_model.S(.bin), {name}_model.h")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("containers", nargs="*", help="model containers (default: every data/*.tstt)")
    args = ap.parse_args()
    containers = args.containers or sorted(glob.glob(os.path.join(ROOT, "data", "*.tstt")))
    if not containers:
        raise SystemExit("no .tstt files in data/")
    for container in containers:
        embed(container)


if __name__ == "__main__":
    main()
